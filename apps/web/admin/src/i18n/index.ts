function isLocalePair(value: LocalePair | LocaleTree): value is LocalePair {
  return Array.isArray(value)
}

function resolveLocale<T extends LocaleTree>(tree: T, language: 0 | 1): Resolved<T> {
  const resolved = Object.fromEntries(
    Object.entries(tree).map(([key, value]) => [
      key,
      isLocalePair(value) ? value[language] : resolveLocale(value, language),
    ]),
  )
  return resolved as Resolved<T>
}

