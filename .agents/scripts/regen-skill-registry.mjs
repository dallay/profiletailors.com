#!/usr/bin/env node
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import process from 'node:process'

const DEFAULT_SKILLS_DIR = '.agents/skills'
const DEFAULT_OUTPUT = '.agents/skill-registry.md'
const FRONTMATTER_PATTERN = /^---\n([\s\S]*?)\n---(?:\n|$)/
const DESCRIPTION_PATTERN = /^description:\s*(.*)$/
const METADATA_PATTERN = /^  ([\w-]+):\s*(.*)$/

const parseArguments = (args) => {
  const options = { skillsDir: DEFAULT_SKILLS_DIR, output: DEFAULT_OUTPUT, check: false }
  for (let index = 0; index < args.length; index += 1) {
    const argument = args[index]
    if (argument === '--skills-dir' || argument === '--output') {
      const value = args[index + 1]
      if (!value) throw new Error(`${argument} requires a path`)
      options[argument === '--skills-dir' ? 'skillsDir' : 'output'] = value
      index += 1
    } else if (argument === '--check') {
      options.check = true
    } else if (argument === '--help') {
      options.help = true
    } else {
      throw new Error(`Unknown argument: ${argument}`)
    }
  }
  return options
}

const usage = () => process.stdout.write('Usage: regen-skill-registry.mjs [--skills-dir <dir>] [--output <file>] [--check]\n')
const scalar = (value) => value.trim().replace(/^['"]|['"]$/g, '')
const parseSkill = (file, folder) => {
  const content = readFileSync(file, 'utf8')
  const frontmatter = content.match(FRONTMATTER_PATTERN)?.[1]
  if (!frontmatter) throw new Error(`Missing frontmatter: ${file}`)
  const lines = frontmatter.split(/\r?\n/)
  const name = scalar(lines.find((line) => line.startsWith('name:'))?.slice(5) || '')
  const descriptionIndex = lines.findIndex((line) => line.startsWith('description:'))
  if (!name || descriptionIndex < 0) throw new Error(`Missing canonical fields: ${file}`)
  const descriptionLine = lines[descriptionIndex].match(DESCRIPTION_PATTERN)?.[1] || ''
  const descriptionLines = []
  if (descriptionLine.startsWith('>') || descriptionLine.startsWith('|')) {
    for (const line of lines.slice(descriptionIndex + 1)) {
      if (!line.startsWith('  ')) break
      descriptionLines.push(line)
    }
  }
  const description = descriptionLine.startsWith('>') || descriptionLine.startsWith('|')
    ? descriptionLines.join(' ').trim()
    : scalar(descriptionLine)
  const metadata = {}
  for (const line of lines) {
    const match = line.match(METADATA_PATTERN)
    if (match) metadata[match[1]] = scalar(match[2])
  }
  if (name !== folder || !description || !metadata.category || !metadata.family || !metadata.source || !metadata.version) {
    throw new Error(`Non-canonical frontmatter: ${file}`)
  }
  return { name, description, ...metadata }
}

const collectSkills = (skillsDir) => {
  if (!existsSync(skillsDir)) throw new Error(`Skills directory does not exist: ${skillsDir}`)
  return readdirSync(skillsDir, { withFileTypes: true })
    .filter((entry) => entry.isDirectory())
    .map((entry) => ({ folder: entry.name, file: resolve(skillsDir, entry.name, 'SKILL.md') }))
    .filter(({ file }) => existsSync(file))
    .map(({ folder, file }) => parseSkill(file, folder))
    .sort((left, right) => left.name.localeCompare(right.name))
}

const compactRule = (description) => description.split(/[.!?](?:\s|$)/, 1)[0].trim() || description
const render = (skills) => {
  const rows = skills.map((skill) => `| \`${skill.name}\` | ${skill.category} | ${skill.family} | ${skill.source} | ${skill.version} | ${compactRule(skill.description)} |`)
  return [
    '# Skill Registry — profiletailors.com',
    '<!-- AUTO-GENERATED by .agents/scripts/regen-skill-registry.mjs -->',
    `> Source: \.agents/skills/*/SKILL.md (${skills.length} top-level skills).`,
    '> This file is generated; change the source skill frontmatter and rerun the generator.',
    '',
    '## Compact Rules',
    '',
    '| Skill | Category | Family | Source | Version | Description |',
    '|---|---|---|---|---|---|',
    ...rows,
    '',
  ].join('\n')
}

const main = () => {
  const options = parseArguments(process.argv.slice(2))
  if (options.help) {
    usage()
    return 0
  }
  const skills = collectSkills(resolve(options.skillsDir))
  const output = resolve(options.output)
  const expected = render(skills)
  if (options.check) {
    if (!existsSync(output) || readFileSync(output, 'utf8') !== expected) {
      process.stderr.write(`Registry drift detected: ${options.output}\n`)
      return 1
    }
    process.stdout.write(`Registry is current: ${skills.length} top-level skills\n`)
    return 0
  }
  writeFileSync(output, expected)
  process.stdout.write(`Generated ${options.output} from ${skills.length} top-level skills\n`)
  return 0
}

try {
  process.exitCode = main()
} catch (error) {
  process.stderr.write(`${error.message}\n`)
  process.exitCode = 2
}
